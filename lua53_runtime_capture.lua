-- Wrap string.pack to handle unsigned overflow (convert negative to unsigned)
local original_string_pack = string.pack
string.pack = function(fmt, ...)
    local args = {...}

    -- Force all numeric arguments to unsigned range if they're negative
    for i, v in ipairs(args) do
        if type(v) == "number" and v < 0 then
            -- Convert negative to unsigned 32-bit
            args[i] = v % (2^32)
        elseif type(v) == "number" and v > 2^31 then
            -- Already large positive, might need to modulo for smaller types
            -- Keep as is, the format will handle it
        end
    end

    -- Use pcall to catch and handle errors
    local ok, result = pcall(original_string_pack, fmt, table.unpack(args))
    if ok then
        return result
    else
        -- If still failing, try forcing all numbers to proper unsigned values
        for i, v in ipairs(args) do
            if type(v) == "number" then
                if v < 0 then
                    args[i] = (v % (2^32)) & 0xFFFFFFFF
                elseif v > 0xFFFFFFFF then
                    args[i] = v & 0xFFFFFFFF
                end
            end
        end
        local ok2, result2 = pcall(original_string_pack, fmt, table.unpack(args))
        if ok2 then
            return result2
        else
            error(result .. " (fmt=" .. fmt .. ")")
        end
    end
end

-- Add missing bit32 functions (countlz and countrz are Luau-specific)
bit32.countlz = function(a)
    a = (a or 0) & 0xFFFFFFFF
    if a == 0 then return 32 end
    local n = 0
    if a <= 0x0000FFFF then n = n + 16; a = a << 16 end
    if a <= 0x00FFFFFF then n = n + 8; a = a << 8 end
    if a <= 0x0FFFFFFF then n = n + 4; a = a << 4 end
    if a <= 0x3FFFFFFF then n = n + 2; a = a << 2 end
    if a <= 0x7FFFFFFF then n = n + 1 end
    return n
end

bit32.countrz = function(a)
    a = (a or 0) & 0xFFFFFFFF
    if a == 0 then return 32 end
    local n = 0
    if (a & 0x0000FFFF) == 0 then n = n + 16; a = a >> 16 end
    if (a & 0x000000FF) == 0 then n = n + 8; a = a >> 8 end
    if (a & 0x0000000F) == 0 then n = n + 4; a = a >> 4 end
    if (a & 0x00000003) == 0 then n = n + 2; a = a >> 2 end
    if (a & 0x00000001) == 0 then n = n + 1 end
    return n
end

