local function write_array(arr, name, max_len)
    max_len = max_len or 3000
    if type(arr) ~= "table" then
        outfile:write(string.format("  %s = %s,\n", name, tostring(arr)))
        return
    end

    local len = 0
    local indices = {}
    for k in pairs(arr) do
        len = len + 1
        if type(k) == "number" then
            table.insert(indices, k)
        end
    end
    table.sort(indices)

    outfile:write(string.format("  %s = { -- %d entries\n", name, len))

    local written = 0
    for _, i in ipairs(indices) do
        if written >= max_len then break end
        local v = arr[i]
        if v ~= nil then
            if type(v) == "string" then
                local s = v
                if #s > 80 then s = string.sub(s, 1, 80) .. "..." end
                s = string.gsub(s, "\\", "\\\\")
                s = string.gsub(s, "\n", "\\n")
                s = string.gsub(s, "\r", "\\r")
                s = string.gsub(s, '"', '\\"')
                s = string.gsub(s, "[%c]", function(c)
                    return string.format("\\x%02X", string.byte(c))
                end)
                outfile:write(string.format('    [%d] = "%s",\n', i, s))
            elseif type(v) == "number" then
                outfile:write(string.format("    [%d] = %s,\n", i, tostring(v)))
            elseif type(v) == "boolean" then
                outfile:write(string.format("    [%d] = %s,\n", i, tostring(v)))
            end
            written = written + 1
        end
    end

    if len > max_len then
        outfile:write(string.format("    -- ... %d more entries truncated\n", len - max_len))
    end
    outfile:write("  },\n")
end

